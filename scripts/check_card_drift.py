def _load_allowlist():
    for line in _ALLOWLIST_SOURCE.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        path, phase, count = line.rsplit("|", 2)
        ALLOWLIST[path] = (phase, int(count))


_load_allowlist()


# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

def repo_relative(path):
    try:
        return os.path.relpath(os.path.realpath(path), REPO).replace(os.sep, "/")
    except ValueError:
        return path


def parts_of(rel_path):
    return [p for p in rel_path.split("/") if p]


def inside_app(rel_path):
    """True only for the app target — compared component-wise, so the sibling
    'Iconik EmployeeTests' target is NOT swept up by a string prefix."""
    parts = parts_of(rel_path)
    return len(parts) > 1 and parts[0] == "Iconik Employee"


def in_exempt_dir(rel_path):
    """Component-wise, so a directory named DesignSystemScratch is not exempt."""
    return any(part in EXEMPT_DIRS for part in parts_of(rel_path))


# ---------------------------------------------------------------------------
# Detection
# ---------------------------------------------------------------------------

def find_cards(text):
    """Return [(line_number, line_text)] for every hand-rolled card container."""
    raw = text.splitlines()

    # Measure distance in CODE lines only. `keep` maps a compacted index back to
    # the real line number so reports still point at the right place.
    code, keep = [], []
    for index, line in enumerate(raw):
        if COMMENT.match(line) or not line.strip():
            continue
        code.append(line)
        keep.append(index)

    # A marker suppresses the nearest following card. Recorded against the next
    # code line so it travels with the construct it explains.
    suppressed_code_lines = set()
    for index, line in enumerate(raw):
        if not ALLOW_MARKER.match(line):
            continue
        for position, original in enumerate(keep):
            if original > index:
                for offset in range(0, PROXIMITY + 1):
                    if position + offset < len(code):
                        suppressed_code_lines.add(position + offset)
                break

    hits = []
    seen = set()

    def window(position, span):
        return max(0, position - span), min(len(code), position + span + 1)

    for position, line in enumerate(code):
        if position in suppressed_code_lines:
            continue

        low, high = window(position, PROXIMITY)

        if SHADOW.search(line) and any(ROUNDING.search(code[j]) for j in range(low, high)):
            number = keep[position] + 1
            if number not in seen:
                seen.add(number)
                hits.append((number, line.strip()))
            continue

        if not ROUNDING.search(line) or EDGE_ONLY.search(line):
            continue

        near_low, near_high = window(position, 2)
        as_background = any(BACKGROUND.search(code[j]) for j in range(near_low, position + 1))
        if not as_background:
            continue
        filled = any(FILL.search(code[j]) for j in range(position, near_high))
        shaped = any("in:" in code[j] for j in range(position, near_high))
        if not (filled or shaped):
            continue

        number = keep[position] + 1
        if number not in seen:
            seen.add(number)
            hits.append((number, line.strip()))

    return hits


