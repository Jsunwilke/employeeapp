#!/usr/bin/env python3
"""
The card-drift gate  (AMB.2, 2026-07-25)

WHY THIS EXISTS
    A design system was already built for this app once. cardStyle() shipped
    during the audit roadmap's Phase 3 and NOTHING EVER CALLED IT, while 115
    hand-rolled card backgrounds went on being written across 39 files. The
    lesson was not "write a design system" — that was done, and it failed. A
    design system with no enforcement is decoration.

    So this gate fails a write that hand-rolls a card. Existing cards are
    grandfathered per file WITH THEIR CURRENT COUNT, so a grandfathered file can
    shrink but never grow: converting is allowed, adding card number eight to
    DashboardWidgets is not. Each AMB phase deletes its entry as it converts.

WHAT COUNTS AS A HAND-ROLLED CARD
    Two shapes, both real in this codebase:

      SHADOWED      a rounding and a .shadow( close together —
                    .cornerRadius(12) + .shadow(...), or
                    RoundedRectangle(...).fill(...).shadow(...)

      ROUNDED FILL  a rounding used as a BACKGROUND, shadow or not —
                    .background(.ultraThinMaterial, in: RoundedRectangle(...))
                    .background(RoundedRectangle(...).fill(...))

    The second rule was added after an audit showed the shadow rule alone had
    roughly half the recall it claimed: EIGHT of the ten cards AMB.2 itself
    converted carry no shadow, and the Ambient idiom IS a shadowless material
    fill. A gate blind to the app's dominant card shape is worse than no gate,
    because it reports green.

    A rounding that is only an edge (.strokeBorder / .stroke) or a mask
    (.clipShape) is not a container and never counts. .ambientCard(...) trips
    nothing, because it contains neither token at the call site — the sanctioned
    path is invisible to the gate and every other path is not.

HOW IT RUNS
    hook     (default) PreToolUse on Write|Edit. Reads the payload on stdin,
             reconstructs what the file WOULD contain after the edit, and exits
             2 to block. FAILS OPEN on every error — a broken gate must never
             stop work.
    --sweep  scan the app; exit 1 if any file exceeds its allowance. Run this
             before declaring a phase done; it is also the only thing that
             catches a card written by a shell command, which the hook cannot
             see (it only matches Write and Edit).
    --list   print every card including grandfathered ones, and emit a ready-to
             -paste ALLOWLIST. The allowlist is GENERATED from the rule rather
             than hand-written, so the green start is a fact, not a hope.

    Modelled on ~/.claude/hooks/protect-captura-files.sh (Python too, despite
    the extension) — same contract: JSON on stdin, fail open, exit 2 plus an
    explanatory sentence on stderr.
"""

import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP_DIR = os.path.join(REPO, "Iconik Employee")

# Directories allowed to build containers.
#   DesignSystem  is where the one card lives.
#   DesignLab     is the mockup harness (D10). Its whole job is to prototype
#                 treatments the primitive cannot yet express so the operator
#                 can choose one — gating it would defeat the hard gate it
#                 serves. A treatment that survives review gets promoted INTO
#                 AmbientCard before the real screens are converted.
EXEMPT_DIRS = ("DesignSystem", "DesignLab")

# How far apart two tokens can sit and still be one card, counted in CODE lines
# — comment lines are removed before measuring. They used to count, which meant
# a long comment explaining a card pushed its own tokens out of range and
# silently hid it. That had already happened once, inside this repo, on the
# first day.
PROXIMITY = 5

ROUNDING = re.compile(r"RoundedRectangle\s*\(|\.cornerRadius\s*\(")
SHADOW = re.compile(r"\.shadow\s*\(")
BACKGROUND = re.compile(r"\.background\s*\(")
FILL = re.compile(r"\.fill\s*\(")
EDGE_ONLY = re.compile(r"\.strokeBorder\s*\(|\.stroke\s*\(|\.clipShape\s*\(")
COMMENT = re.compile(r"^\s*(//|\*|/\*)")

# Per-SITE opt-out for things that are rounded and filled but are not cards: a
# selection chip, a photo hero, a keyboard key, a drop shadow on a glyph.
# Must be a COMMENT and must carry a reason, so it cannot be tripped by a string
# literal and cannot be dropped in without saying why.
ALLOW_MARKER = re.compile(r"^\s*(?://|\*|/\*)\s*ambient-allow:\s*\S+")

# ---------------------------------------------------------------------------
# Grandfathered: path -> (owning phase, number of cards allowed to remain).
#
