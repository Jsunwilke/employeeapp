def resulting_content(payload):
    """What the file will contain once this tool call lands."""
    tool = payload.get("tool_name", "")
    tool_input = payload.get("tool_input") or {}
    if not isinstance(tool_input, dict):
        return None, None
    path = tool_input.get("file_path") or ""
    if not isinstance(path, str) or not path:
        return None, None

    if tool == "Write":
        content = tool_input.get("content")
        return path, content if isinstance(content, str) else ""

    if tool == "Edit":
        old = tool_input.get("old_string")
        new = tool_input.get("new_string")
        old = old if isinstance(old, str) else ""
        new = new if isinstance(new, str) else ""
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as handle:
                current = handle.read()
        except OSError:
            return path, new
        if tool_input.get("replace_all"):
            return path, current.replace(old, new)
        return path, current.replace(old, new, 1)

    return None, None


def run_hook():
    try:
        payload = json.load(sys.stdin)
    except Exception:
        return 0
    if not isinstance(payload, dict):
        return 0
    if payload.get("tool_name") not in ("Write", "Edit"):
        return 0

    path, content = resulting_content(payload)
    if not path or not path.lower().endswith(".swift"):
        return 0

    rel = repo_relative(path)
    if not inside_app(rel) or in_exempt_dir(rel):
        return 0

    hits = find_cards(content or "")
    if not hits:
        return 0

    # The test is "does this edit make it WORSE", not "is this file clean".
    #
    # Comparing against the file on disk is what lets a conversion proceed one
    # card at a time: turning card 1 of 7 into .ambientCard leaves six behind,
    # and a clean-file test would refuse that edit — locking the gate against
    # the very work it exists to encourage. It also means a file can never gain
    # a card, which is the property that actually matters. The allowlist counts
    # are the ratchet for --sweep; this is the ratchet for each edit.
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            before = len(find_cards(handle.read()))
    except OSError:
        before = 0  # new file

    if len(hits) <= before:
        return 0

    phase, allowance = ALLOWLIST.get(rel, (None, 0))
    added = hits[before:]
    where = "\n".join(f"    line {number}: {text}" for number, text in added[:6])
    if phase:
        headline = (
            f"BLOCKED by check-card-drift: {rel} is grandfathered at {allowance} "
            f"hand-rolled card(s) for {phase}. This edit takes it from {before} "
            f"to {len(hits)}. A grandfathered file may shrink, never grow."
        )
    else:
        headline = (
            f"BLOCKED by check-card-drift: this edit adds a hand-rolled card to "
            f"{rel} ({before} before, {len(hits)} after)."
        )

    print(
        f"{headline}\n{where}\n\n"
        "A rounded, filled container is a CARD, and this app has exactly one: "
        ".ambientCard(density:state:border:glow:fillWidth:contentAlignment:) in "
        "DesignSystem/AmbientCard.swift. Densities are .hero / .roomy / .compact.\n\n"
        "If it genuinely is NOT a card — a button, a keyboard key, a selection "
        "chip, a drop shadow on an image — put a reasoned marker on the line "
        "above it:\n"
        "    // ambient-allow: this is the FAB, not a card\n\n"
        "If the primitive cannot express what you need, EXTEND AmbientCard.swift. "
        "Do not hand-roll one here, and do not widen the allowlist in "
        "scripts/check_card_drift.py without asking the operator first — that "
        "blinds the gate to the whole file, which is how the previous card "
        "modifier ended up with zero adopters.",
        file=sys.stderr,
    )
    return 2


# ---------------------------------------------------------------------------
# Sweep
# ---------------------------------------------------------------------------

def walk_swift():
    for root, dirs, files in os.walk(APP_DIR):
        dirs[:] = [d for d in dirs if d not in EXEMPT_DIRS]
        for name in files:
            if name.lower().endswith(".swift"):
                yield os.path.join(root, name)


def scan_all():
    found = {}
    for path in sorted(walk_swift()):
        rel = repo_relative(path)
        if in_exempt_dir(rel):
            continue
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as handle:
                hits = find_cards(handle.read())
        except OSError as exc:
            print(f"  ! could not read {rel}: {exc}", file=sys.stderr)
            continue
        if hits:
            found[rel] = hits
    return found


def run_scan(emit_allowlist):
    found = scan_all()
    over, dead = [], []

    for rel, hits in sorted(found.items()):
        phase, allowance = ALLOWLIST.get(rel, (None, 0))
        if len(hits) > allowance:
            over.append((rel, hits, phase, allowance))

    for rel, (phase, allowance) in ALLOWLIST.items():
        actual = len(found.get(rel, []))
        if actual < allowance:
            dead.append((rel, phase, allowance, actual))

    if emit_allowlist:
        total = sum(len(v) for v in found.values())
        print(f"{len(found)} files, {total} hand-rolled cards.\n")
        print("Paste into _ALLOWLIST_SOURCE:\n")
        for rel, hits in sorted(found.items()):
            phase = ALLOWLIST.get(rel, ("UNASSIGNED", 0))[0]
            print(f"{rel}|{phase}|{len(hits)}")
        print()

    status = 0
    if over:
        print(f"CARD DRIFT — {len(over)} file(s) over their allowance:")
        for rel, hits, phase, allowance in over:
            label = f"grandfathered {allowance} for {phase}" if phase else "not grandfathered"
            print(f"  {rel}  ({len(hits)} found, {label})")
            for number, text in hits[allowance:]:
                print(f"      line {number}: {text}")
        status = 1
    else:
        print("Card drift: clean. No file exceeds its allowance.")

    # Reported even when the sweep is red: a shrunk allowance is a phase that
    # did work and forgot to tighten the gate behind it.
    if dead:
        print(f"\n{len(dead)} allowance(s) now too generous — tighten or delete:")
        for rel, phase, allowance, actual in dead:
            print(f"  {rel}  [{phase}]  allows {allowance}, found {actual}")

    return status


def main():
    if "--sweep" in sys.argv:
        return run_scan(emit_allowlist=False)
    if "--list" in sys.argv:
        return run_scan(emit_allowlist=True)
    return run_hook()


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as exc:  # never wedge the session
        print(f"[check-card-drift] failing open: {exc}", file=sys.stderr)
        sys.exit(0)
